/**
 * Aplica as traduções ao DOM usando atributos data-i18n.
 * Recolhe todos os nós ANTES de modificar o DOM para evitar
 * que elementos orphaned percam a sua tradução.
 * @param {string} lang - código do idioma
 */
function applyTranslations(lang) {
  const t = translations[lang] || translations['pt'];

  // Actualiza o atributo lang do <html> e dir para RTL em árabe
  document.documentElement.lang = lang;
  document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';

  // Recolhe todos os pares [elemento, chave] ANTES de modificar o DOM
  // Isto evita que um pai substitua o innerHTML e orphane os filhos
  const items = [];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      items.push({ el, value: t[key] });
    }
  });

  // Aplica as traduções — a dois passes garante que pais são processados
  // antes dos filhos sem problemas de DOM orphaning
  items.forEach(({ el, value }) => {
    el.innerHTML = value;
  });

  // Traduz placeholders (data-i18n-ph)
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (t[key] !== undefined) {
      el.placeholder = t[key];
    }
  });

  // Traduz aria-labels (data-i18n-aria)
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    if (t[key] !== undefined) {
      el.setAttribute('aria-label', t[key]);
    }
  });

  // Persiste a escolha
  localStorage.setItem('vivemo_lang', lang);
}

/**
 * Inicializa o seletor de idioma na navbar.
 */
export function initI18n() {
  const select = document.getElementById('langSelect');
  if (!select) return;

  const saved = localStorage.getItem('vivemo_lang') || 'pt';
  select.value = saved;

  Promise.resolve().then(() => applyTranslations(saved));

  select.addEventListener('change', () => {
    applyTranslations(select.value);
  });
}
